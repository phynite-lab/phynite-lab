FIXTURES = json.loads((Path(__file__).resolve().parents[2] / 'tests/fixtures/crystal-database-imports.json').read_text())


def imported_node(database='cod'):
    # Shared fixture is generated by the actual TypeScript search/normalization
    # service and checked against it by tests/crystal-database.test.ts.
    material = copy.deepcopy(FIXTURES['cod' if database == 'cod' else 'materialsProject'])
    name = 'Silicon reference'
    structure = {'name': name, 'formula': material['formula'], 'atoms': material['atoms'], 'lattice': material['lattice'],
                 'periodic': material['lattice']['periodic'], 'source': material['source'], 'externalId': material['materialId'],
                 'sourceUrl': material['sourceUrl'], 'sourceData': material['sourceData'], 'provenance': material['provenance']}
    return {'id': 'structure_database_1', 'kind': 'structure', 'name': name, 'position': {'x': 60, 'y': 80}, 'configuration': {'structure': structure}, 'resources': []}


class LocalAiStructureImportTests(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.services = LocalServices(Path(directory.name), 'http://127.0.0.1:8792', 'http://127.0.0.1:3000')
        self.api = PhyniteApi(self.services)
        self.ai = AiWorkspace(self.api)
        self.workflow = ProjectWorkflowApi(self.api)
        self.owner = self.services.owner
        self.project = json.loads(self.api.create_project(self.owner, {'name': 'Import review fixture'})['body'])['project']['id']
        self.conversation = self.ai.put(self.owner, 'AI_CONVERSATION', 'aic_import', {'projectKey': 'project:' + self.project, 'mode': 'approval', 'activeRunId': 'air_import', 'title': 'Import a crystal'})
        self.run = self.ai.put(self.owner, 'AI_RUN', 'air_import', {'conversationId': self.conversation['id'], 'status': 'running', 'expiresAt': int(time.time()) + 900, 'leaseHash': digest('fixture-lease'), 'taskMode': 'work', 'modelId': 'fixture-model'})

    def payload(self, node=None, base_revision=0):
        return {'kind': 'import_structure', 'stamp': self.ai.context(self.owner, self.conversation)['stamp'], 'payload': {'baseRevision': base_revision, 'node': node or imported_node()}, 'toolCallId': 'import_fixture'}

    def prepare(self, payload=None, conversation=None, run=None):
        return self.ai.prepare(self.owner, conversation or self.conversation, run or self.run, payload or self.payload())

    def test_approval_preserves_source_attaches_owned_resource_and_replay_is_idempotent(self):
        node = imported_node()
        original = copy.deepcopy(node)
        with patch('urllib.request.urlopen', side_effect=AssertionError('An approved import must not fetch a URL')):
            action = self.prepare(self.payload(node))
            self.assertEqual(action['status'], 'pending')
            review = action['after']['structure']
            self.assertEqual(review['atomCount'], 1)
            self.assertEqual(review['provenance']['id'], 'cod-9000001')
            self.assertEqual(review['provenance']['sourceSha256'], node['configuration']['structure']['sourceData']['sha256'])
            self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))
            result = self.ai.execute(self.owner, self.conversation, action, action['payloadHash'])
            self.assertEqual(result['status'], 'succeeded', result)
            self.assertEqual(result['result']['nodeId'], node['id'])
            stored = self.services.get_item(self.owner, 'STRUCTURE', result['result']['structureId'])
            saved = self.workflow.load(self.owner, self.project)
            self.assertEqual(saved['revision'], 1)
            self.assertEqual(saved['workflow']['nodes'][0]['configuration'], original['configuration'])
            self.assertEqual(saved['workflow']['nodes'][0]['resources'], [{'kind': 'structure', 'id': stored['id'], 'sha256': stored['sha256']}])
            raw = self.services.s3.get_object(Bucket=self.services.bucket, Key=stored['objectKey'])['Body'].read()
            self.assertEqual(hashlib.sha256(raw).hexdigest(), stored['sha256'])
            self.assertEqual(json.loads(raw), original['configuration']['structure'])
            self.assertEqual(result['result']['provenance'], original['configuration']['structure']['provenance'])
            replay = self.ai.execute(self.owner, self.conversation, result, action['payloadHash'])
            self.assertEqual(replay['id'], result['id'])
            self.assertEqual(len(self.services.list_owner_items(self.owner, 'STRUCTURE')), 1)
            self.assertEqual(self.workflow.load(self.owner, self.project)['revision'], 1)
        self.assertEqual(node, original)

    def test_materials_project_source_is_supported_without_server_credentials(self):
        action = self.prepare(self.payload(imported_node('materials-project')))
        result = self.ai.execute(self.owner, self.conversation, action, action['payloadHash'])
        self.assertEqual(result['status'], 'succeeded', result)
        self.assertEqual(result['result']['provenance']['database'], 'materials-project')

    def test_all_optimade_sources_match_the_shared_normalizer_contract(self):
        fixtures = json.loads((Path(__file__).resolve().parents[2] / 'tests/fixtures/crystal-optimade-imports.json').read_text())['materials']
        for source, material in fixtures.items():
            with self.subTest(source=source):
                structure = imported_node()['configuration']['structure']
                structure.update({'formula': material['formula'], 'atoms': material['atoms'], 'lattice': material['lattice'], 'periodic': material['lattice']['periodic'], 'source': material['source'], 'externalId': material['materialId'], 'sourceUrl': material['sourceUrl'], 'sourceData': material['sourceData'], 'provenance': material['provenance']})
                database_structure(structure)
                forged = copy.deepcopy(structure)
                forged['sourceUrl'] = forged['provenance']['url'] = 'https://untrusted.invalid/structure'
                with self.assertRaises(ApiError):
                    database_structure(forged)
        material = fixtures['alexandria']
        node = imported_node()
        node['configuration']['structure'].update({'formula': material['formula'], 'atoms': material['atoms'], 'lattice': material['lattice'], 'periodic': material['lattice']['periodic'], 'source': material['source'], 'externalId': material['materialId'], 'sourceUrl': material['sourceUrl'], 'sourceData': material['sourceData'], 'provenance': material['provenance']})
        with patch('urllib.request.urlopen', side_effect=AssertionError('Approval must not fetch an untrusted URL')):
            action = self.prepare(self.payload(node))
            result = self.ai.execute(self.owner, self.conversation, action, action['payloadHash'])
        self.assertEqual(result['status'], 'succeeded', result)
        self.assertEqual(result['result']['provenance']['database'], 'alexandria')

    def test_import_appends_without_replacing_existing_input_and_retains_original_source_date(self):
        graph = self.workflow.load(self.owner, self.project)['workflow']
        existing = {'id': 'original_input', 'kind': 'structure', 'name': 'Preserved draft', 'position': {'x': 0, 'y': 0}, 'configuration': {'exactInput': 'retained verbatim'}, 'resources': []}
        graph['nodes'].append(copy.deepcopy(existing))
        self.workflow.save(self.owner, self.project, {'workflow': graph, 'baseRevision': 0})
        node = imported_node()
        node['configuration']['structure']['provenance']['sourceUpdatedAt'] = '2026-01-02'
        action = self.prepare(self.payload(node, base_revision=1))
        result = self.ai.execute(self.owner, self.conversation, action, action['payloadHash'])
        self.assertEqual(result['status'], 'succeeded', result)
        saved = self.workflow.load(self.owner, self.project)
        self.assertEqual(saved['workflow']['nodes'][0], existing)
        self.assertEqual(saved['workflow']['nodes'][1]['id'], node['id'])
        self.assertEqual(result['result']['provenance']['sourceUpdatedAt'], '2026-01-02')

    def test_mismatched_provenance_source_ids_and_hosts_are_rejected_before_mutation(self):
        cases = [
            lambda document: document['sourceData'].update(content='changed source bytes'),
            lambda document: document['sourceData'].update(sha256='a' * 64),
            lambda document: document['provenance'].update(sourceSha256='b' * 64),
            lambda document: document['provenance'].update(structureSha256='invalid'),
            lambda document: document.update(externalId='cod-9000000'),
            lambda document: document['provenance'].update(database=['cod']),
            lambda document: document['provenance'].update(id='cod-9000000'),
            lambda document: document.update(sourceUrl='https://example.test/source'),
            lambda document: document['provenance'].update(url='https://example.test/source'),
            lambda document: document['provenance'].update(termsUrl='https://example.test/terms'),
            lambda document: document['provenance'].update(termsUrl='https://www.crystallography.net:443/cod/'),
            lambda document: document['sourceData'].update(filename='../9000001.cif'),
            lambda document: document['sourceData'].update(format='json'),
            lambda document: document['provenance'].update(retrievedAt='yesterday'),
        ]
        for mutate in cases:
            node = imported_node(); mutate(node['configuration']['structure'])
            with self.subTest(node=node), self.assertRaises(ApiError):
                self.prepare(self.payload(node))
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))
        self.assertFalse(self.services.list_owner_items(self.owner, 'AI_ACTION'))
        self.assertEqual(self.workflow.load(self.owner, self.project)['revision'], 0)

    def test_invalid_geometry_extra_configuration_and_resource_bindings_are_rejected(self):
        cases = [
            lambda node: node['configuration']['structure']['atoms'][0].update(x=float('nan')),
            lambda node: node['configuration']['structure']['atoms'][0].update(species='X'),
            lambda node: node['configuration']['structure']['lattice'].update(a=0),
            lambda node: node['configuration']['structure']['lattice'].update(vectors=[[1, 0, 0], [2, 0, 0], [0, 0, 1]]),
            lambda node: node['configuration']['structure'].update(periodic=[True, True, False]),
            lambda node: node['configuration'].update(computeTarget='shared'),
            lambda node: node['configuration']['structure'].update(url='https://example.test/source'),
            lambda node: node['resources'].append({'kind': 'structure', 'id': 'someone_else'}),
            lambda node: node.update(legacy={'localId': 'old', 'editor': 'dft'}),
            lambda node: node.update(kind='scf'),
        ]
        for mutate in cases:
            node = imported_node(); mutate(node)
            with self.subTest(node=node), self.assertRaises(ApiError):
                self.prepare(self.payload(node))
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))

    def test_chat_and_read_only_tasks_cannot_prepare_imports(self):
        with self.assertRaises(ApiError) as denied:
            self.prepare(conversation={**self.conversation, 'mode': 'chat'})
        self.assertEqual(denied.exception.code, 'AI_PERMISSION_DENIED')
        for mode in ('plan', 'research', 'summary'):
            with self.subTest(mode=mode), self.assertRaises(ApiError) as denied:
                self.prepare(run={**self.run, 'taskMode': mode})
            self.assertEqual(denied.exception.code, 'AI_TASK_READ_ONLY')
        self.assertFalse(self.services.list_owner_items(self.owner, 'AI_ACTION'))

    def test_revision_change_expires_approval_and_foreign_conversation_cannot_execute(self):
        action = self.prepare()
        with self.assertRaises(ApiError) as denied:
            self.ai.execute(self.owner, {**self.conversation, 'id': 'aic_other'}, action, action['payloadHash'])
        self.assertEqual(denied.exception.code, 'AI_NOT_FOUND')
        graph = self.workflow.load(self.owner, self.project)['workflow']
        self.workflow.save(self.owner, self.project, {'workflow': graph, 'baseRevision': 0})
        result = self.ai.execute(self.owner, self.conversation, action, action['payloadHash'])
        self.assertEqual(result['status'], 'expired')
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))

    def test_stale_revision_duplicate_nodes_and_non_canvas_scope_are_rejected(self):
        with self.assertRaises(ApiError) as stale:
            self.prepare(self.payload(base_revision=1))
        self.assertEqual(stale.exception.code, 'AI_CONTEXT_CHANGED')
        graph = self.workflow.load(self.owner, self.project)['workflow']
        graph['nodes'].append(imported_node())
        self.workflow.save(self.owner, self.project, {'workflow': graph, 'baseRevision': 0})
        with self.assertRaises(ApiError) as duplicate:
            self.prepare(self.payload(base_revision=1))
        self.assertEqual(duplicate.exception.code, 'INVALID_WORKFLOW')
        with self.assertRaises(ApiError) as scope:
            self.ai.validate_action(self.owner, {**self.conversation, 'projectKey': 'md:' + self.project}, 'import_structure', {'baseRevision': 1, 'node': imported_node()})
        self.assertEqual(scope.exception.code, 'AI_PROJECT_REQUIRED')
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))

    def test_failed_graph_save_rolls_back_import_and_changed_revision_does_not_create_resource(self):
        data = self.payload()['payload']
        action = {'kind': 'import_structure', 'id': 'aia_fixture'}
        with patch.object(ProjectWorkflowApi, 'save', side_effect=ApiError(409, 'Changed elsewhere', 'WORKFLOW_CONFLICT')):
            with self.assertRaises(ApiError):
                self.ai.perform(self.owner, self.conversation, action, data)
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))
        self.assertEqual(self.workflow.load(self.owner, self.project)['revision'], 0)
        graph = self.workflow.load(self.owner, self.project)['workflow']
        self.workflow.save(self.owner, self.project, {'workflow': graph, 'baseRevision': 0})
        with self.assertRaises(ApiError) as changed:
            self.ai.perform(self.owner, self.conversation, action, data)
        self.assertEqual(changed.exception.code, 'AI_CONTEXT_CHANGED')
        self.assertFalse(self.services.list_owner_items(self.owner, 'STRUCTURE'))


if __name__ == '__main__':
    unittest.main()
