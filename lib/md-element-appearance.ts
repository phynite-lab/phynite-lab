export function normalizedMdElementSymbol(species: string) {
  const match = species.trim().match(/^([A-Z][a-z]?)/i);
  if (!match) return species.trim() || 'X';
  return `${match[1][0].toUpperCase()}${match[1].slice(1).toLowerCase()}`;
}

export function mdAppearanceFor(species: string): MdElementAppearance {
  const element = normalizedMdElementSymbol(species);
  const preset = mdElementAppearance[element];
  if (preset) return preset;
  const hue = Array.from(element).reduce((sum, letter) => sum + letter.charCodeAt(0), 0) % 360;
  return { color: `hsl(${hue} 38% 62%)`, radius: 1.2 };
}
